export function translateCommonTerms(text: string, isEN: boolean): string {
  if (!text) return "";
  if (!isEN) return text;
  let translated = text;

  // Replacements for hotels
  translated = translated.replace(/hotel\s*\*?\s*3\s*\/\s*setaraf/gi, "3-Star Hotel or equivalent");
  translated = translated.replace(/hotel\s*\*?\s*3\s*\/\s*equivalent/gi, "3-Star Hotel or equivalent");
  translated = translated.replace(/hotel\s*\*?\s*setaraf/gi, "Hotel or equivalent");
  translated = translated.replace(/Hotel\s*\*\*\*\s*\/\s*setaraf/gi, "3-Star Hotel or equivalent");
  translated = translated.replace(/hotel\s*\*\*\*\s*\/\s*setaraf/gi, "3-Star Hotel or equivalent");

  // Replacements for meals/programs
  translated = translated.replace(/MAKAN PAGI/gi, "BREAKFAST");
  translated = translated.replace(/MAKAN SIANG/gi, "LUNCH");
  translated = translated.replace(/MAKAN MALAM/gi, "DINNER");
  translated = translated.replace(/KEBERANGKATAN/gi, "DEPARTURE");
  translated = translated.replace(/PENJEMPUTAN/gi, "PICKUP");

  return translated;
}
